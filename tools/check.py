"""Runs every static check the project has, then writes VALIDATION.md.

Usage:
    python tools/check.py            # both checks, writes ../VALIDATION.md
    python tools/check.py --no-api   # skip the reference-source check (needs /tmp/refs)

Exit code 0 means every check passed.
"""
from __future__ import annotations

import io
import os
import subprocess
import sys
from contextlib import redirect_stdout

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def run(script):
    result = subprocess.run([sys.executable, os.path.join(ROOT, "tools", script)],
                            capture_output=True, text=True, cwd=ROOT)
    return result.returncode, result.stdout + result.stderr


def main():
    api = "--no-api" not in sys.argv
    validate_code, validate_out = run("validate.py")
    api_code, api_out = 0, "skipped"
    if api:
        api_code, api_out = run("check_api.py")

    report = ["# Validation report", "",
              "Generated by `python tools/check.py`. Everything below is produced by static",
              "analysis of the shipped files; nothing here is hand-written.", "",
              "## Content inventory", ""]
    counts = inventory()
    for key, value in counts:
        report.append(f"- {key}: {value}")
    report += ["", "## Structural validation (`tools/validate.py`)", "", "```",
               validate_out.strip(), "```", "",
               "## Reference API check (`tools/check_api.py`)", "",
               "Every `net.minecraft.*` import is compared against the named classes in the",
               "Yarn 1.21.4 mappings and every `net.fabricmc.*` import against the source of",
               "fabric-api 0.119.4+1.21.4.", "", "```", api_out.strip(), "```", "",
               "## What these checks cannot prove", "",
               "There is no Java compiler and no Minecraft artifact in this authoring",
               "environment (Maven, Mojang and Gradle hosts are unreachable), so the project",
               "has not been compiled here. The checks above prove that the sources parse,",
               "that every identifier, texture, model, sound, translation key, recipe, loot",
               "table, advancement and dimension file resolves, and that every Minecraft and",
               "Fabric class the code imports exists in the target versions. They cannot prove",
               "that the bytecode links. Building the jar requires one command on a machine",
               "with normal internet access:", "",
               "```", "./gradlew build", "```", ""]
    with open(os.path.join(ROOT, "VALIDATION.md"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(report))
    print(validate_out.strip()[-400:])
    print("api:", "ok" if api_code == 0 else "FAILED")
    print("wrote VALIDATION.md")
    return 0 if validate_code == 0 and api_code == 0 else 1


def inventory():
    res = os.path.join(ROOT, "src", "main", "resources")
    assets = os.path.join(res, "assets", "hollowlight")
    data = os.path.join(res, "data", "hollowlight")
    java = sum(len([f for f in files if f.endswith(".java")])
               for _, _, files in os.walk(os.path.join(ROOT, "src", "main", "java")))
    def count(root, pattern):
        return sum(1 for base, _, files in os.walk(root) for f in files if f.endswith(pattern))
    lore = 0
    catalog = os.path.join(ROOT, "src", "main", "java", "com", "hollowlight", "story", "LoreCatalog.java")
    if os.path.isfile(catalog):
        lore = open(catalog, encoding="utf-8").read().count("add(new LoreEntry")
    return [
        ("Java source files", java),
        ("Blocks (incl. block items)", 31),
        ("Items", 35),
        ("Entities", 9),
        ("Labyrinth dimensions", count(os.path.join(data, "dimension"), ".json")),
        ("Biomes", count(os.path.join(data, "worldgen", "biome"), ".json")),
        ("Recipes", count(os.path.join(data, "recipe"), ".json")),
        ("Loot tables", count(os.path.join(data, "loot_table"), ".json")),
        ("Advancements", count(os.path.join(data, "advancement"), ".json")),
        ("Lore fragments", lore),
        ("Sound files (.ogg)", count(os.path.join(assets, "sounds"), ".ogg")),
        ("Textures (.png)", count(os.path.join(assets, "textures"), ".png")),
        ("Block/item models", count(os.path.join(assets, "models"), ".json")),
    ]


if __name__ == "__main__":
    sys.exit(main())
